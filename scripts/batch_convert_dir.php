$converted = 0;
$skipped = 0;

$iterator = new RecursiveIteratorIterator(
    new RecursiveDirectoryIterator($rootDir, RecursiveDirectoryIterator::SKIP_DOTS),
    RecursiveIteratorIterator::SELF_FIRST
);

foreach ($iterator as $file) {
    if (!$file->isFile() || $file->getExtension() !== 'php') {
        continue;
    }

    $path = $file->getRealPath();
    
    // 排除目录
    $skip = false;
    foreach ($excludeDirs as $excludeDir) {
        if (str_contains($path, $excludeDir)) {
            $skip = true;
            break;
        }
    }
    if ($skip) continue;
    // 跳过转换脚本本身
    if (str_ends_with($path, 'convert_tc_to_sc.php') || str_ends_with($path, 'batch_convert_dir.php') || str_ends_with($path, 'batch_convert.php')) {
        continue;
    }

    $content = file_get_contents($path);
    $newContent = str_replace(array_keys($replacements), array_values($replacements), $content);
    
    if ($newContent !== $content) {
        file_put_contents($path, $newContent);
        $converted++;
        echo "Converted: " . basename($path) . "\n";
    } else {
        $skipped++;
    }
}

echo "\nDone. Converted: $converted, Skipped: $skipped\n";
